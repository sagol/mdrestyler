"""Regenerate the cross-restyle example's reports from its committed profiles, passages and takes.

  python3 run.py                  write the reports under restyle/ and results/
  python3 run.py --check          exit 1 when a committed report differs from what the run produces
  python3 run.py rebuild --work DIR
                                  fetch the two books, check their hashes, rescan them into DIR and compare
                                  the profiles' measures and guards with the committed ones

The reports run the skill in this repository unless MDRESTYLER names another command, such as `mdrestyler`.
Standard library only."""
import argparse
import hashlib
import json
import os
import re
import shlex
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
TOOL = HERE.parents[1] / 'skills/mdrestyler/scripts/mdrestyler.py'
AUTHORS = ('twain', 'james')
DIRECTIONS = {'twain-to-james': ('twain', 'james'), 'james-to-twain': ('james', 'twain')}
TAKES = ('take-1.md', 'take-2.md', 'take-3.md')


def command():
    if os.environ.get('MDRESTYLER'):
        return shlex.split(os.environ['MDRESTYLER'])
    return [sys.executable, str(TOOL)]


def run(*args, ok=(0, 1)):
    env = dict(os.environ, PYTHONHASHSEED='0')
    done = subprocess.run(command() + list(args), cwd=HERE, env=env, capture_output=True, text=True, encoding='utf-8')
    if done.returncode not in ok:
        sys.exit(f'mdrestyler {" ".join(args)} exited {done.returncode}:\n{done.stderr}')
    return done.stdout.replace(str(HERE) + os.sep, '')


def chosen(direction):
    found = re.search(r'^Chosen: (take-\d\.md)$', (HERE / 'restyle' / direction / 'choice.md').read_text(encoding='utf-8'), re.M)
    if not found:
        sys.exit(f'restyle/{direction}/choice.md names no take on a "Chosen: take-N.md" line')
    return found.group(1)


def book(unit, profile):
    with tempfile.TemporaryDirectory() as folder:
        units = Path(folder) / 'units.txt'
        units.write_text(unit + '\n', encoding='utf-8')
        return run('book', '.', '--profile', f'profiles/{profile}', '--list', str(units), '--within', 'p90')


def rounded(value):
    if isinstance(value, float):
        return round(value, 4)
    if isinstance(value, dict):
        return {k: rounded(v) for k, v in value.items()}
    if isinstance(value, list):
        return [rounded(v) for v in value]
    return value


def measured(text, profile):
    report = json.loads(run('check', '--profile', f'profiles/{profile}', text, '--json'))
    narration = report['registers']['narration']
    p90 = narration['calibration_quantiles']['p90']
    distance = narration['voice_distance']['distance']
    return rounded({
        'words': report['words'],
        'voice_distance': report['voice_distance']['distance'],
        'narration_distance': distance,
        'narration_closer_than': narration['voice_distance']['closer_than_share'],
        'narration_p90': p90,
        'restyle': 'beyond' if distance > p90 else 'within',
        'narration_outside': sum(m['status'].startswith('outside') for m in narration['measures']),
        'narration_measures': {m['measure']: {'label': m['label'], 'value': m['value'], 'low': m['low'], 'high': m['high'],
                                              'status': m['status']} for m in narration['measures']},
        'copy_guard_runs': len(report['copy_guard_hits']),
    })


def texts():
    rows = []
    for direction, (source, target) in DIRECTIONS.items():
        pick = chosen(direction)
        rows.append((f'passages/{source}.md', f'{source} passage', None))
        for take in TAKES:
            rows.append((f'restyle/{direction}/{take}', f'{direction} {take[:-3]}' + (' (chosen)' if take == pick else ''), direction))
    return rows


def matrix():
    data = {path: {'label': label, 'profiles': {p: measured(path, p) for p in AUTHORS}} for path, label, _ in texts()}
    lines = ['# Every text against both profiles', '',
             'Generated by `run.py`. Distances are mdrestyler\'s robust distances from each profile\'s source chapters; '
             'the narration distance leaves dialogue out. *Closer than* is the share of the profile\'s own source chapters '
             'whose narration lies farther from the rest. *Restyle* reads the narration distance against the 90th percentile '
             'of the profile\'s own chapters. Copy-guard runs are 8-word runs shared with the profile\'s scanned book.', '']
    for profile in AUTHORS:
        lines += [f'## Against the {profile} profile', '',
                  '| Text | Words | Voice distance | Narration distance | Closer than | Restyle | Narration measures outside | Copy-guard runs |',
                  '|---|---|---|---|---|---|---|---|']
        for path, row in data.items():
            m = row['profiles'][profile]
            lines.append(f"| {row['label']} | {m['words']} | {m['voice_distance']:.2f} | {m['narration_distance']:.2f} | "
                         f"{m['narration_closer_than']:.0%} | {m['restyle']} (p90 {m['narration_p90']:.2f}) | "
                         f"{m['narration_outside']} | {m['copy_guard_runs']} |")
        lines.append('')
    for direction, (source, target) in DIRECTIONS.items():
        before = data[f'passages/{source}.md']['profiles'][target]['narration_measures']
        after = data[f'restyle/{direction}/{chosen(direction)}']['profiles'][target]['narration_measures']
        lines += [f'## {direction}: the chosen take\'s narration against the {target} profile', '',
                  '| Measure | Source passage | Chosen take | Target range | Before | After |', '|---|---|---|---|---|---|']
        for key, b in before.items():
            a = after[key]
            lines.append(f"| {b['label']} | {b['value']:.3g} | {a['value']:.3g} | {b['low']:.3g} to {b['high']:.3g} | {b['status']} | {a['status']} |")
        lines.append('')
    return '\n'.join(lines), json.dumps(data, indent=1, ensure_ascii=False) + '\n'


def reports():
    out = {}
    for direction, (source, target) in DIRECTIONS.items():
        pick = chosen(direction)
        folder = f'restyle/{direction}'
        out[f'{folder}/before.md'] = book(f'passages/{source}.md', target)
        out[f'{folder}/rank.md'] = run('rank', '--profile', f'profiles/{target}', *(f'{folder}/{t}' for t in TAKES))
        out[f'{folder}/check.md'] = run('check', '--profile', f'profiles/{target}', f'{folder}/{pick}')
        out[f'{folder}/after.md'] = book(f'{folder}/{pick}', target)
    out['results/matrix.md'], out['results/matrix.json'] = matrix()
    return out


def rebuild(work):
    sources = json.loads((HERE / 'sources.json').read_text(encoding='utf-8'))
    work = Path(work).resolve()
    if HERE in work.parents or work == HERE:
        sys.exit('--work must lie outside the example folder')
    differs = False
    for name, source in sources.items():
        epub = work / 'epub' / f'{name}.epub'
        epub.parent.mkdir(parents=True, exist_ok=True)
        if not epub.is_file():
            request = urllib.request.Request(source['url'], headers={'User-Agent': 'mdrestyler-example'})
            with urllib.request.urlopen(request, timeout=60) as response:
                epub.write_bytes(response.read())
        digest = hashlib.sha256(epub.read_bytes()).hexdigest()
        if digest != source['sha256']:
            print(f'{name}: the fetched book differs from the scanned one ({digest}); the publisher may have rebuilt it, '
                  'so the profile below will differ too')
        profile = work / 'profiles' / name
        done = subprocess.run(command() + ['scan', '--reference', str(epub), '--out', str(profile), '--work', str(work / 'samples' / name),
                                           '--replace'], capture_output=True, text=True, encoding='utf-8')
        if done.returncode:
            sys.exit(f'scan of {name} exited {done.returncode}:\n{done.stderr}')
        for path in (work / 'samples' / name).glob('samples.*.md'):
            path.unlink()
        fresh = json.loads((profile / 'author-profile.en.json').read_text(encoding='utf-8'))
        kept = json.loads((HERE / 'profiles' / name / 'author-profile.en.json').read_text(encoding='utf-8'))
        fresh.pop('built'), kept.pop('built')
        for source_record in fresh['sources']:
            source_record['file'] = kept['sources'][0]['file']
        same = fresh == kept and (profile / 'copy-guard.en.json').read_bytes() == (HERE / 'profiles' / name / 'copy-guard.en.json').read_bytes()
        print(f'{name}: measures and guard {"match the committed profile" if same else "differ from the committed profile"}')
        differs |= not same
    return 1 if differs else 0


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('action', nargs='?', choices=['rebuild'], help='rebuild the profiles from the books')
    parser.add_argument('--work', help='with rebuild: a folder outside the example for the books, profiles and samples')
    parser.add_argument('--check', action='store_true', help='compare the committed reports with a fresh run')
    args = parser.parse_args()
    if args.action == 'rebuild':
        if not args.work:
            parser.error('rebuild needs --work')
        return rebuild(args.work)
    stale = []
    for name, text in reports().items():
        path = HERE / name
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != text:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding='utf-8')
    if stale:
        print('stale: ' + ', '.join(stale))
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
